export const useAiGatewayI18n = () => {
  const { locale, setLocale } = useLocale()

  const t = (source: string) => locale.value === 'zh-CN' ? (zh[source] ?? source) : source
  const l = (english: string, chinese: string) => locale.value === 'zh-CN' ? chinese : english

  return {
    l,
    locale,
    setLocale,
    t,
  }
}
